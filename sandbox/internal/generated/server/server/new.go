// NewServer builds the http surface of the sandbox: Routes, one entry per
// directory under sandbox/internal/routeslist holding a route.yaml, at any
// depth, built by that package's generated NewRoute — in run order, the
// lowest `priority` first and by name within one rung — Serve, which hands the
// server to Deps.OpinatedAgnosServer.ServerMain against them, and Fail, which
// hands one failure to the project's own handler for it. The dispatch is the
// lib's; everything it runs is the project's. Generated by
// `agnos build` — do not edit by hand.
func NewServer(sandbox *api.Sandbox) api.Server {
	server := api.Server{}

	server.Routes = []*api.Route{
		routeslist_client_ip.NewRoute(sandbox),
		routeslist_security_headers.NewRoute(sandbox),
		routeslist_same_origin.NewRoute(sandbox),
		routeslist_api_authentication.NewRoute(sandbox),
		routeslist_authentication.NewRoute(sandbox),
		routeslist_api_root_guard.NewRoute(sandbox),
		routeslist_root_guard.NewRoute(sandbox),
		routeslist_add_backoffice_user.NewRoute(sandbox),
		routeslist_add_backoffice_user_page.NewRoute(sandbox),
		routeslist_api_add_backoffice_user.NewRoute(sandbox),
		routeslist_api_edit_backoffice_user.NewRoute(sandbox),
		routeslist_api_get_backoffice_user.NewRoute(sandbox),
		routeslist_api_list_backoffice_users.NewRoute(sandbox),
		routeslist_api_me.NewRoute(sandbox),
		routeslist_api_remove_backoffice_user.NewRoute(sandbox),
		routeslist_create_backoffice_api_token.NewRoute(sandbox),
		routeslist_create_backoffice_api_token_page.NewRoute(sandbox),
		routeslist_edit_backoffice_user.NewRoute(sandbox),
		routeslist_edit_backoffice_user_page.NewRoute(sandbox),
		routeslist_health.NewRoute(sandbox),
		routeslist_home.NewRoute(sandbox),
		routeslist_list_backoffice_api_tokens.NewRoute(sandbox),
		routeslist_list_backoffice_users.NewRoute(sandbox),
		routeslist_login.NewRoute(sandbox),
		routeslist_logout.NewRoute(sandbox),
		routeslist_remove_backoffice_user.NewRoute(sandbox),
		routeslist_revoke_backoffice_api_token.NewRoute(sandbox),
		routeslist_frontend.NewRoute(sandbox),
	}

	// The props are built per call and read the sandbox as the server runs:
	// sandbox.Server, so a caller that replaced one of its fields is
	// followed, and Std by pointer, so a silenced Std.Log stays silenced.
	server.Serve = func(props api.ServeProps) error {
		return sandbox.Deps.OpinatedAgnosServer.ServerMain(opinatedagnosserver.MainProps{
			Server: &sandbox.Server,
			Serve:  props,
			NewProps: func() any {
				return &routeprops.RouteProps{}
			},
			MatchTrigger: sandbox.Deps.OpinatedAgnosCli.MatchTrigger,
			Std:          &sandbox.Deps.Std,
			Serverdeps:   sandbox.Deps.Serverdeps,
			Signaldeps:   sandbox.Deps.Signaldeps,
		})
	}

	// One failure, one file of sandbox/internal/server/errors/. The switch is
	// the whole of the routing: every Handle* below is written once by
	// `agnos server-init` and is the project's from then on, so
	// changing what a 404 looks like is editing handle_not_found.go and
	// nothing else.
	//
	// A Handle* answers a failure; it never raises one. A failure raised from
	// inside one comes back here and runs it again.
	server.Fail = func(route *api.Route) error {
		response := route.Response

		if route.Failure != nil {
			switch route.Failure.Status {
			case api.StatusNotFound:
				return errors.HandleNotFound(sandbox, route, response)
			case api.StatusMethodNotAllowed:
				return errors.HandleMethodNotAllowed(sandbox, route, response)
			case api.StatusBadRequest:
				return errors.HandleBadRequest(sandbox, route, response)
			case api.StatusUnauthorized:
				return errors.HandleUnauthorized(sandbox, route, response)
			case api.StatusForbidden:
				return errors.HandleForbidden(sandbox, route, response)
			case api.StatusPayloadTooLarge:
				return errors.HandleTooLarge(sandbox, route, response)
			case api.StatusUnsupportedMedia:
				return errors.HandleWrongContentType(sandbox, route, response)
			}
		}

		return errors.HandleServerError(sandbox, route, response)
	}

	return server
}
