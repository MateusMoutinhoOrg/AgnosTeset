package cli

import (
	api "github.com/MateusMoutinhoOrg/AgnosTeset/sandbox/api"
	"github.com/MateusMoutinhoOrg/AgnosTeset/sandbox/internal/cli/errors"
	add_backoffice_user "github.com/MateusMoutinhoOrg/AgnosTeset/sandbox/internal/commands/add_backoffice_user"
	help "github.com/MateusMoutinhoOrg/AgnosTeset/sandbox/internal/commands/help"
	help_flag "github.com/MateusMoutinhoOrg/AgnosTeset/sandbox/internal/commands/help_flag"
	start_server "github.com/MateusMoutinhoOrg/AgnosTeset/sandbox/internal/commands/start_server"
	version "github.com/MateusMoutinhoOrg/AgnosTeset/sandbox/internal/commands/version"
)

// NewCli builds the cli surface of the sandbox: Commands, one entry per
// sandbox/internal/commands/<name>/ built by that package's generated
// NewCommand, in run order; Fail, which hands a failure to the project's own
// handler for it; and CliMain, the dispatch that reads a command line against
// them. Generated by `agnos build` — do not edit by hand.
func NewCli(sandbox *api.Sandbox) api.Cli {
	cli := api.Cli{}

	cli.Commands = []*api.Command{
		help_flag.NewCommand(sandbox),
		add_backoffice_user.NewCommand(sandbox),
		help.NewCommand(sandbox),
		start_server.NewCommand(sandbox),
		version.NewCommand(sandbox),
	}

	cli.Fail = func(command *api.Command) error {
		if command.Failure == nil {
			return errors.HandleFailure(sandbox, command, command.Response)
		}
		switch command.Failure.Kind {
		case api.NotFoundFailure:
			return errors.HandleNotFound(sandbox, command, command.Response)
		case api.BadUsageFailure:
			return errors.HandleBadUsage(sandbox, command, command.Response)
		case api.UnknownFlagFailure:
			return errors.HandleUnknownFlag(sandbox, command, command.Response)
		case api.UnexpectedArgFailure:
			return errors.HandleUnexpectedArg(sandbox, command, command.Response)
		}
		return errors.HandleFailure(sandbox, command, command.Response)
	}

	cli.CliMain = func(args []string) int {
		return CliMain(sandbox, args)
	}

	return cli
}
