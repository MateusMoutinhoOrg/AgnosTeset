// NewRoute builds this route's declaration — a 1:1 image of its route.yaml —
// on the empty base of Deps.OpinatedAgnosServer.NewRoute, and closes
// InternalPureHandler over the sandbox as the handler behind it. It is called
// once by sandbox/internal/generated/server/server/new.go, and what it returns
// is one entry of Server.Routes: the declaration alone, which the lib's
// dispatch copies before binding a request onto it.
// Generated by `agnos build` — do not edit by hand; the logic
// lives in InternalPureHandler.go.
func NewRoute(sandbox *api.Sandbox) *api.Route {
	self := sandbox.Deps.OpinatedAgnosServer.NewRoute()

	self.Name = "api_me"
	self.AcceptMethods = []string{"GET"}
	self.Priority = 100
	self.ResponseType = "application/json"
	self.Segments = 3
	self.Pattern = "/api/admin/me"
	self.Category = "Backoffice API"
	self.Help = "Answers the backoffice user of the Bearer token"
	self.LongDescription = ""
	self.Examples = []string{"curl localhost:3000/api/admin/me -H \"Authorization: Bearer $TOKEN\""}
	self.Hidden = false

	self.Paths = []api.Path{
		{
			Id:          "ApiAdminMe",
			Start:       0,
			End:         2,
			Type:        api.StringPath,
			Description: "",
			Trigger:     api.Trigger{Exist: true, Type: api.EqualTrigger, Value: "/api/admin/me", Negate: false, IgnoreCase: false},
		},
	}

	self.Parameters = []api.Parameter{}

	self.Body = api.RouteBody{
		Type:        "none",
		Required:    false,
		MaxBytes:    1048576,
		ContentType: "",
		Schema:      "",
	}

	self.InternalPureHandler = func(props *routeprops.RouteProps, entries *Entries, response *serverdeps.Response) error {
		return InternalPureHandler(sandbox, props, entries, response)
	}

	return self
}
