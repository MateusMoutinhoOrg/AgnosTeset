package backup

import (
	api "github.com/MateusMoutinhoOrg/AgnosTeset/sandbox/api"
	databasedeps "github.com/MateusMoutinhoOrg/AgnosTeset/sandbox/deps/databasedeps"
)

// New builds the backup database from the Props its database.yaml declares and
// closes every method of methods.go over it. It touches no key: a database is
// a value over a prefix, so building one creates nothing until the first
// record is written. Props that Databases.New refuses are reported on stderr,
// and every method of the database then fails rather than panics; verify
// refuses every declaration that would build them.
//
// Generated by `agnos build` — do not edit by hand.
func New(sandbox *api.Sandbox) *Backup {
	props := databasedeps.Props{
		Path:    "data/backup",
		Schemas: []databasedeps.Schema{},
	}

	database, failure := sandbox.Deps.DatabaseDeps.Databases.New(props)
	if failure != nil {
		sandbox.Deps.StdDeps.Eprintf("backup: %s \n", sandbox.Deps.OpinionatedAgnosDatabase.Fail(failure).Error())
	}

	self := Backup{sandbox: sandbox, database: database}

	return &self
}
