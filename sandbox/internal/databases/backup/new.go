package backup

import (
	api "github.com/MateusMoutinhoOrg/AgnosTeset/sandbox/api"
	databasedeps "github.com/MateusMoutinhoOrg/AgnosTeset/sandbox/deps/databasedeps"
)

// New builds the backup database from the Props its database.yaml declares and
// closes every method of methods.go over it. It touches no key: a database is
// a value over a prefix, so building one creates nothing until the first
// record is written. Props that Databases.New refuses are reported on stderr,
// and every method of the database then fails rather than panics; verify
// refuses every declaration that would build them.
//
// Generated by `agnos build` — do not edit by hand.
func New(sandbox *api.Sandbox) *Backup {
	props := databasedeps.Props{
		Path: "data/backup",
		Schemas: []databasedeps.Schema{
			{
				Name: "blob",
				Fields: []databasedeps.Field{
					{Name: "sha", Type: databasedeps.Key, Required: true},
					{Name: "value", Type: databasedeps.Bytes, Required: true},
				},
			},
		},
	}

	database, failure := sandbox.Deps.DatabaseDeps.Databases.New(props)
	if failure != nil {
		sandbox.Deps.StdDeps.Eprintf("backup: %s \n", sandbox.Deps.OpinionatedAgnosDatabase.Fail(failure).Error())
	}

	self := Backup{sandbox: sandbox, database: database}

	self.AddBlob = func(props BlobInput) (BlobRecord, error) {
		return AddBlob(self.sandbox, &self, props)
	}
	self.FindBlobById = func(id int64) (BlobRecord, bool) {
		return FindBlobById(self.sandbox, &self, id)
	}
	self.FindBlobBySha = func(value string) (BlobRecord, bool) {
		return FindBlobBySha(self.sandbox, &self, value)
	}
	self.ListBlobs = func(filter BlobFilter) ([]BlobRecord, error) {
		return ListBlobs(self.sandbox, &self, filter)
	}
	self.ListBlobsPage = func(offset int, limit int) ([]BlobRecord, error) {
		return ListBlobsPage(self.sandbox, &self, offset, limit)
	}
	self.CountBlob = func() (int, error) {
		return CountBlob(self.sandbox, &self)
	}
	self.SetBlobSha = func(id int64, value string) error {
		return SetBlobSha(self.sandbox, &self, id, value)
	}
	self.SetBlobValue = func(id int64, value []byte) error {
		return SetBlobValue(self.sandbox, &self, id, value)
	}
	self.RemoveBlob = func(id int64) error {
		return RemoveBlob(self.sandbox, &self, id)
	}

	return &self
}
